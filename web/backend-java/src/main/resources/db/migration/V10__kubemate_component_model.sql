CREATE TABLE cluster_component_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_id BIGINT NOT NULL,
    component_key VARCHAR(64) NOT NULL,
    status VARCHAR(32) DEFAULT 'not_installed' NOT NULL,
    installed_version VARCHAR(64),
    last_job_id BIGINT,
    last_error_code VARCHAR(128),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cluster_component_states_cluster
        FOREIGN KEY (cluster_id) REFERENCES clusters (id) ON DELETE CASCADE,
    CONSTRAINT fk_cluster_component_states_job
        FOREIGN KEY (last_job_id) REFERENCES jobs (id) ON DELETE SET NULL,
    CONSTRAINT uk_cluster_component_states_cluster_key UNIQUE (cluster_id, component_key),
    CONSTRAINT ck_cluster_component_states_status
        CHECK (status IN ('not_installed', 'installing', 'installed', 'failed'))
);

CREATE INDEX idx_cluster_component_states_job
    ON cluster_component_states (last_job_id);

