    ADD COLUMN config_json CLOB DEFAULT '{}' NOT NULL;

UPDATE cluster_components target
SET enabled = CASE
    WHEN target.enabled = TRUE
      OR EXISTS (
          SELECT 1
          FROM cluster_components legacy
          WHERE legacy.cluster_id = target.cluster_id
            AND legacy.component_key = 'loki'
            AND legacy.enabled = TRUE
      ) THEN TRUE
    ELSE FALSE
END
WHERE target.component_key = 'storage_observability';

DELETE FROM cluster_components legacy
WHERE legacy.component_key = 'loki'
  AND EXISTS (
      SELECT 1
      FROM cluster_components target
      WHERE target.cluster_id = legacy.cluster_id
        AND target.component_key = 'storage_observability'
  );

UPDATE cluster_components
SET component_key = 'storage_observability'
WHERE component_key = 'loki';

