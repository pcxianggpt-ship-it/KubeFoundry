#!/bin/bash

#===============================================================================
# 脚本名称：progress.sh
# 功能：断点续跑进度跟踪函数库
# 作者：KubeFoundry Team
# 版本：1.0.0
#===============================================================================

# 防止重复加载
[ -n "$_PROGRESS_LOADED" ] && return 0
_PROGRESS_LOADED=1

# 进度状态文件路径
PROGRESS_FILE="${PROJECT_ROOT}/.kubefoundry_progress"

#===============================================================================
# 函数：progress_init()
# 功能：初始化进度跟踪（确保状态文件所在目录存在）
#===============================================================================
progress_init() {
    local progress_dir
    progress_dir="$(dirname "$PROGRESS_FILE")"
    if [ ! -d "$progress_dir" ]; then
        mkdir -p "$progress_dir"
    fi
    # 文件不存在则创建空文件
    [ -f "$PROGRESS_FILE" ] || touch "$PROGRESS_FILE"
}

#===============================================================================
# 函数：step_is_done()
# 功能：检查指定步骤是否已完成
# 参数：
#   $1 - 步骤 ID（如 "2.1"）
# 返回值：
#   0 - 已完成
#   1 - 未完成
#===============================================================================
step_is_done() {
    local step_id="$1"
    grep -qx "$step_id" "$PROGRESS_FILE" 2>/dev/null
}

#===============================================================================
# 函数：step_done()
# 功能：标记指定步骤为已完成
# 参数：
#   $1 - 步骤 ID（如 "2.1"）
#===============================================================================
step_done() {
    local step_id="$1"
    echo "$step_id" >> "$PROGRESS_FILE"
}

#===============================================================================
# 函数：progress_reset()
# 功能：清除进度状态文件，用于重新开始
#===============================================================================
progress_reset() {
    if [ -f "$PROGRESS_FILE" ]; then
        rm -f "$PROGRESS_FILE"
        log_info "已清除进度记录，将从头开始执行"
    fi
}

#===============================================================================
# 函数：progress_clean()
# 功能：全部成功后清除进度状态文件
#===============================================================================
progress_clean() {
    if [ -f "$PROGRESS_FILE" ]; then
        rm -f "$PROGRESS_FILE"
    fi
}
